// Turns the same data already shown on the Biomechanical panel, Training
// Plan page, and Race-day Plan page into the generic content model that
// lib/shareCard.js renders as a branded PDF/PNG. Keeping this mapping
// separate from those components means the share endpoint (which only
// sees whatever JSON the client posts) and the pages themselves stay in
// sync with a single definition of "what's in this panel."

function fmtDate(d) {
  return new Date(d).toLocaleDateString("en-US", { month: "long", day: "numeric", year: "numeric" });
}

export function buildBiomechanicalShareContent({ athleteName, insights }) {
  const stats = [];
  if (insights.load?.acwr != null) stats.push({ label: "Acute:chronic load", value: String(insights.load.acwr) });
  const d30 = insights.biomechanics?.windows?.last30Days;
  if (d30?.avgDecouplingPct != null) stats.push({ label: "Aerobic decoupling (30d)", value: `${d30.avgDecouplingPct}%` });
  if (d30?.avgCadenceDriftPct != null) stats.push({ label: "Cadence drift (30d)", value: `${d30.avgCadenceDriftPct}%` });

  const sections = [];
  const ai = insights.ai;
  const badge = ai ? { text: `${ai.risk_level} risk · ${ai.risk_score}/100`, level: ai.risk_level } : null;

  if (ai) {
    sections.push({ heading: "Risk summary", kind: "paragraph", text: ai.risk_summary });
    sections.push({
      heading: "Analysis",
      kind: "columns",
      columns: [
        { heading: "Risk factors", items: ai.risk_factors || [] },
        { heading: "Recovery plan", items: ai.recovery_plan || [] },
        { heading: "Nutrition plan", items: ai.nutrition_plan || [] },
      ],
    });
    if (ai.training_adjustment?.length) {
      sections.push({ heading: "Recommended training adjustment", kind: "list", items: ai.training_adjustment });
    }
  } else {
    sections.push({
      heading: "Analysis",
      kind: "paragraph",
      text: insights.aiError ? `Couldn't generate an AI analysis right now (${insights.aiError}).` : "No AI analysis yet.",
    });
  }

  return {
    kind: "biomechanical",
    eyebrow: "Overtraining Shield",
    title: athleteName ? `${athleteName}'s Training Health` : "Training Health",
    subtitle: `Generated ${fmtDate(Date.now())}`,
    stats,
    badge,
    sections,
    footerNote: "Generated by an AI model from recent training patterns — a wellness heuristic, not medical advice.",
  };
}

export function buildTrainingPlanShareContent({ athleteName, goal, plan }) {
  const sections = [{ heading: "Overview", kind: "paragraph", text: plan.overview }];

  sections.push({
    heading: "Phases",
    kind: "list",
    items: plan.phases.map((p) => {
      const extras = [p.focus, p.weekly_volume_guidance, p.weekly_time_estimate ? `~${p.weekly_time_estimate}` : null]
        .filter(Boolean)
        .join(" — ");
      const workouts = (p.key_workouts || []).join("; ");
      return `${p.name} (${p.weeks}): ${extras}${workouts ? ` · Key workouts: ${workouts}` : ""}`;
    }),
  });

  sections.push({
    heading: "Guidelines",
    kind: "columns",
    columns: [
      { heading: "Recovery guidelines", items: plan.recovery_guidelines || [] },
      { heading: "Nutrition plan", items: plan.nutrition_plan || [] },
      { heading: "Pre-race preparation", items: plan.pre_race_prep || [] },
      { heading: "Race day strategy", items: plan.race_day_strategy || [] },
    ],
  });

  return {
    kind: "training-plan",
    eyebrow: "AI Progressive Training Plan",
    title: goal?.eventName || "Upcoming event",
    subtitle: [
      goal?.targetDistance,
      goal?.goalTime ? `Goal: ${goal.goalTime}` : null,
      goal?.eventDate ? fmtDate(goal.eventDate) : null,
    ].filter(Boolean).join(" · "),
    stats: [],
    badge: null,
    sections,
    footerNote: "Generated by an AI model from recent training patterns — a training heuristic, not a certified coaching or medical service.",
  };
}

export function buildRaceDayShareContent({ athleteName, goal, plan }) {
  const sections = [{ heading: "Pacing strategy", kind: "paragraph", text: plan.pacing_strategy }];

  sections.push({
    heading: "Segment pacing",
    kind: "list",
    items: (plan.segment_pacing || []).map((s) => `${s.segment_label}: ${s.target_pace} — ${s.notes}`),
  });

  sections.push({
    heading: "Fueling & conditions",
    kind: "columns",
    columns: [
      { heading: "Fueling plan", items: plan.fueling_plan || [] },
      { heading: "Heat & altitude adjustments", items: plan.heat_altitude_adjustments || [] },
      { heading: "Pre-race checklist", items: plan.pre_race_checklist || [] },
      { heading: "Contingencies", items: plan.contingency_notes || [] },
    ],
  });

  return {
    kind: "race-day",
    eyebrow: "Race-Day Pacing & Fueling Plan",
    title: goal?.eventName || "Race day",
    subtitle: [
      goal?.targetDistance,
      goal?.goalTime ? `Goal: ${goal.goalTime}` : null,
      goal?.eventDate ? fmtDate(goal.eventDate) : null,
    ].filter(Boolean).join(" · "),
    stats: [],
    badge: null,
    sections,
    footerNote: "Generated by an AI model from your own training data and the conditions entered — a pacing heuristic, not a certified coaching service.",
  };
}
